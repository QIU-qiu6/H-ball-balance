void OLED_Clear(void)
{
    memset(g_oled_buffer, 0, sizeof(g_oled_buffer));
}

void OLED_ShowLine(u8 row, const char *text)
{
    u8 x = 0;
    u8 glyph[5];
    u8 i;
    u16 base;

    if (row >= 8) return;
    base = (u16)row * 128u;
    memset(&g_oled_buffer[base], 0, 128);
    while (*text && x <= 122) {
        Glyph5x7(*text++, glyph);
        for (i = 0; i < 5; i++) g_oled_buffer[base + x + i] = glyph[i];
        x = (u8)(x + 6);
    }
}

static void OLED_DrawChineseGlyph(u8 x0, u8 y0, const u8 glyph[32])
{
    u8 x, y;
    u16 bits;
    u16 index;

    for (y = 0; y < 16; y++) {
        bits = ((u16)glyph[(u16)y * 2u] << 8) |
               glyph[(u16)y * 2u + 1u];
        for (x = 0; x < 16; x++) {
            if (bits & ((u16)0x8000u >> x)) {
                index = (u16)((y0 + y) >> 3) * 128u + x0 + x;
                g_oled_buffer[index] |= (u8)(1u << ((y0 + y) & 7u));
            }
        }
    }
}

void OLED_ShowChineseLine(u8 row16, OLED_ZhText text)
{
    const u8 *phrase = g_zh_menu;
    u8 length = sizeof(g_zh_menu);
    u8 i;
    u16 base;

    if (row16 >= 4) return;
    switch (text) {
    case OLED_ZH_Q3:          phrase = g_zh_q3;       length = sizeof(g_zh_q3); break;
    case OLED_ZH_HOLD:        phrase = g_zh_hold;     length = sizeof(g_zh_hold); break;
    case OLED_ZH_CENTER_HOLD: phrase = g_zh_center;   length = sizeof(g_zh_center); break;
    case OLED_ZH_CAPTURE:     phrase = g_zh_capture;  length = sizeof(g_zh_capture); break;
    case OLED_ZH_CAPTURED:    phrase = g_zh_captured; length = sizeof(g_zh_captured); break;
    case OLED_ZH_FREE_HOLD:   phrase = g_zh_free;     length = sizeof(g_zh_free); break;
    case OLED_ZH_RETURN_ZERO: phrase = g_zh_return;   length = sizeof(g_zh_return); break;
    case OLED_ZH_BALL_LOST:   phrase = g_zh_lost;     length = sizeof(g_zh_lost); break;
    case OLED_ZH_ESTOP:       phrase = g_zh_estop;    length = sizeof(g_zh_estop); break;
    case OLED_ZH_FAULT:       phrase = g_zh_fault;    length = sizeof(g_zh_fault); break;
    case OLED_ZH_MENU:
    default:                  phrase = g_zh_menu;     length = sizeof(g_zh_menu); break;
    }

    base = (u16)row16 * 256u;
    memset(&g_oled_buffer[base], 0, 256);
    if (length > 8u) length = 8u;
    for (i = 0; i < length; i++) {
        OLED_DrawChineseGlyph((u8)(i * 16u), (u8)(row16 * 16u),
                              g_zh_glyphs[phrase[i]]);
    }
}

u8 OLED_Refresh(void)
{
    u8 page, x, ok;
    for (page = 0; page < 8; page++) {
        if (!OLED_WriteCommand((u8)(0xB0u + page)) ||
            !OLED_WriteCommand(0x00) || !OLED_WriteCommand(0x10)) return 0;
        I2C_Start();
        ok = I2C_WriteByte(OLED_ADDR_WRITE);
        if (ok) ok = I2C_WriteByte(0x40);
        for (x = 0; ok && x < 128; x++) {
            ok = I2C_WriteByte(g_oled_buffer[(u16)page * 128u + x]);
        }
        I2C_Stop();
        if (!ok) return 0;
    }
    return 1;
}

u8 OLED_Init(void)
{
    GPIO_InitTypeDef gpio;
    static const u8 init_cmds[] = {
        0xAE,0x20,0x02,0xB0,0xC8,0x00,0x10,0x40,0x81,0x7F,
        0xA1,0xA6,0xA8,0x3F,0xA4,0xD3,0x00,0xD5,0x80,0xD9,
        0xF1,0xDA,0x12,0xDB,0x40,0x8D,0x14,0xAF
    };
    u8 i;

    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOB, ENABLE);
    gpio.GPIO_Pin = OLED_SCL_PIN | OLED_SDA_PIN;
    gpio.GPIO_Mode = GPIO_Mode_Out_OD;
    gpio.GPIO_Speed = GPIO_Speed_2MHz;
    GPIO_Init(GPIOB, &gpio);
    SCL_High(); SDA_High();

    for (i = 0; i < sizeof(init_cmds); i++) {
        if (!OLED_WriteCommand(init_cmds[i])) return 0;
    }
    OLED_Clear();
    OLED_ShowLine(0, "GIMBAL BOOT");
    return OLED_Refresh();
}
